import { cpSync, existsSync, mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { Application } from 'typedoc';
import { renderApiCard } from './lib/api-card.mjs';
import { compareTrees, listFiles } from './lib/markdown.mjs';
import { verifyApiCoverage } from './lib/coverage.mjs';
import { installExactRendering } from './lib/exact-rendering.mjs';
import { verifyRenderedSyntax } from './lib/syntax.mjs';

const directory = dirname(fileURLToPath(import.meta.url));
const root = resolve(directory, '../..');
const destination = join(root, 'docs/reference');
const cardPath = join(root, 'docs/agent/api-card.md');
const check = process.argv.includes('--check');
if (process.argv.slice(2).some(argument => argument !== '--check')) throw new Error('Usage: node generate.mjs [--check]');
const temporary = mkdtempSync(join(tmpdir(), 'di-bag-api-'));
const output = join(temporary, 'reference');
process.chdir(directory);

try {
  const app = await Application.bootstrapWithPlugins({ options: join(directory, 'typedoc.json') });
  installExactRendering(app);
  app.options.setValue('out', output);
  app.options.setValue('docsRoot', temporary);
  const project = await app.convert();
  if (!project || app.logger.hasErrors()) throw new Error('API conversion failed');
  app.validate(project);
  if (app.logger.hasErrors() || app.logger.hasWarnings()) throw new Error('API validation failed');
  await app.generateOutputs(project);
  if (app.logger.hasErrors() || app.logger.hasWarnings()) throw new Error('API Markdown generation failed');
  const coverage = verifyApiCoverage(project, root, output);
  const declarationCount = verifyRenderedSyntax(output);
  writeFileSync(join(output, 'api-coverage.json'), JSON.stringify(coverage, null, 2) + '\n');
  for (const file of listFiles(output).filter(file => file.endsWith('.md'))) {
    const content = readFileSync(join(output, file), 'utf8');
    if (/\b(?:constraint|provider|module|token)Invariant\b/.test(content)) {
      throw new Error(`${file}: internal compiler witness leaked into public documentation`);
    }
    writeFileSync(join(output, file), '<!-- Generated by npm run docs:generate. Edit source comments, not this file. -->\n\n' + content);
  }
  const card = renderApiCard(project, JSON.parse(readFileSync(join(directory, 'api-card-tasks.json'), 'utf8')));
  if (check) {
    const differences = compareTrees(output, destination);
    if (!existsSync(cardPath) || readFileSync(cardPath, 'utf8') !== card) differences.push('changed: docs/agent/api-card.md');
    if (differences.length) throw new Error(`Generated API Markdown is stale. Run npm run docs:generate.\n${differences.join('\n')}`);
    console.log('Generated API Markdown and the API card are current; all entry points and callable overloads are covered.');
  } else {
    writeFileSync(cardPath, card);
    rmSync(destination, { recursive: true, force: true });
    mkdirSync(destination, { recursive: true });
    cpSync(output, destination, { recursive: true });
    console.log(`Generated ${listFiles(destination).filter(file => file.endsWith('.md')).length} API Markdown pages with verified public coverage and ${declarationCount} valid TypeScript blocks.`);
  }
} finally {
  rmSync(temporary, { recursive: true, force: true });
}
