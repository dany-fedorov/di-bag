import { cardBudget, codeFragment } from './agent-docs.mjs';

/** The runtime surface the card covers, besides the exported error classes. */
export const surfaceGroups = [
  { name: 'DiBagApi', receiver: 'DiBag', title: 'DiBag facade' },
  { name: 'Builder', receiver: 'builder', title: 'Builder' },
  { name: 'Container', receiver: 'container', title: 'Container' },
];

const header = '<!-- Generated by npm run docs:generate from JSDoc in src/ and tools/docs/api-card-tasks.json. Do not edit. -->';
const partText = parts => (parts ?? []).map(part => part.kind === 'inline-tag' ? `\`${part.text}\`` : part.text).join('');
const tags = (comment, name) => comment?.blockTags.filter(tag => tag.tag === name) ?? [];
const line = reflection => reflection.sources?.[0]?.line ?? 0;
const anchor = name => name.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');

/** Call signatures of a method, a function-typed property, or a property typed by a callable alias. */
function callSignatures(reflection) {
  if (reflection.signatures) return reflection.signatures;
  const type = reflection.type;
  if (type?.declaration?.signatures) return type.declaration.signatures;
  if (type?.reflection) return callSignatures(type.reflection);
  return [];
}

function parameters(signature) {
  // `invalid` rest parameters only reject explicit `never` generics; `this` parameters only constrain the receiver.
  return (signature?.parameters ?? []).filter(parameter => parameter.name !== 'invalid' && parameter.name !== 'this')
    .map(parameter => parameter.flags.isRest ? `...${parameter.name}` : parameter.flags.isOptional ? `${parameter.name}?` : parameter.name);
}

function firstSentence(comment) {
  const summary = partText(comment?.summary).replace(/\s+/g, ' ').trim();
  return summary.match(/^.*?[.!?](?=\s|$)/)?.[0] ?? summary;
}

function examples(comment) {
  return tags(comment, '@example').flatMap(tag => [...partText(tag.content).matchAll(/```(?:ts|typescript)\n([\s\S]*?)\n?```/g)].map(match => match[1]));
}

function entry(reflection, group, receiver) {
  const comments = [{ comment: reflection.comment }, ...(reflection.signatures ?? []).map(signature => ({ comment: signature.comment, signature }))]
    .filter(item => item.comment);
  // The comment carrying the example supplies the summary and, for an overload, the signature.
  const carrier = comments.find(item => examples(item.comment).length);
  const name = receiver ? `${receiver}.${reflection.name}` : reflection.name;
  const codes = receiver
    ? [...new Set(comments.flatMap(item => tags(item.comment, '@throws')).flatMap(tag => partText(tag.content).match(/DI_BAG_[A-Z_]+/g) ?? []))]
    : codeLiterals(reflection);
  const signature = carrier?.signature ?? callSignatures(reflection)[0];
  return {
    group, name, id: anchor(name), line: line(reflection),
    title: receiver ? `${name}(${parameters(signature).join(', ')})` : name,
    summary: firstSentence(carrier?.comment ?? comments[0]?.comment),
    examples: carrier ? examples(carrier.comment) : [],
    codes, codeLabel: receiver ? 'Throws' : 'Code',
  };
}

function codeLiterals(reflection) {
  const type = reflection.children?.find(child => child.name === 'code')?.type;
  const members = type?.type === 'union' ? type.types : type ? [type] : [];
  return members.filter(member => member.type === 'literal').map(member => member.value);
}

/** Facade members, builder and container methods, and error classes, each with its card fields. */
export function runtimeSurface(project) {
  const index = project.children?.find(child => child.name === 'index');
  if (!index) throw new Error('API card: missing index entry point');
  const entries = [];
  for (const { name, receiver, title } of surfaceGroups) {
    const reflection = index.children.find(child => child.name === name);
    if (!reflection) throw new Error(`API card: missing ${name}`);
    entries.push(...reflection.children.filter(child => child.name !== 'constructor').map(child => entry(child, title, receiver)).sort((a, b) => a.line - b.line));
  }
  // Kind 128 is a class; type-only classes such as Container are exported as interfaces.
  entries.push(...index.children.filter(child => child.kind === 128).map(child => entry(child, 'Errors')).sort((a, b) => a.line - b.line));
  return entries;
}

/** Render the card; refuses a runtime call without an example, an unknown task call, or a card over budget. */
export function renderApiCard(project, tasks) {
  const entries = runtimeSurface(project);
  const errors = entries.filter(item => !item.examples.length)
    .map(item => `${item.name}: add an @example to its JSDoc; every runtime call needs one for the API card`);
  const names = new Map(entries.map(item => [item.name, item]));
  if (!Array.isArray(tasks) || !tasks.length) errors.push('api-card-tasks.json must be a non-empty array');
  for (const task of Array.isArray(tasks) ? tasks : []) {
    if (typeof task?.task !== 'string' || typeof task.call !== 'string') errors.push(`api-card-tasks.json: ${JSON.stringify(task)} needs a task and exactly one call`);
    else if (!names.has(task.call)) errors.push(`api-card-tasks.json: "${task.task}" names unknown call ${task.call}`);
  }
  if (errors.length) throw new Error(`API card generation failed:\n${errors.join('\n')}`);
  const lines = [
    header, '',
    '# API card {#api-card}', '',
    'Every runtime call of `di-bag`: its summary, the codes it can raise, and an example that type-checks.',
    "An example without an import line uses `import { DiBag } from 'di-bag';`. The rules are in",
    '[AGENTS.md](../../AGENTS.md); each code links to its section in [errors.md](errors.md).', '',
    '## One way per task {#one-way-per-task}', '',
    '| Task | Call |', '| --- | --- |',
    ...tasks.map(task => `| ${task.task} | [\`${names.get(task.call).title}\`](#${names.get(task.call).id}) |`),
  ];
  let group;
  for (const item of entries) {
    if (item.group !== group) lines.push('', `## ${item.group} {#${anchor(item.group)}}`);
    group = item.group;
    const codes = item.codes.length ? ` ${item.codeLabel}: ${item.codes.map(code => `[\`${code}\`](errors.md#${codeFragment(code)})`).join(', ')}.` : '';
    lines.push('', `### \`${item.title}\` {#${item.id}}`, `${item.summary}${codes}`, ...item.examples.flatMap(code => ['```ts', code, '```']));
  }
  const markdown = lines.join('\n') + '\n';
  const count = lines.length;
  if (count > cardBudget) throw new Error(`API card has ${count} lines; the budget is ${cardBudget}. Shorten @example blocks on the runtime surface.`);
  return markdown;
}
