import fs from 'node:fs';
import path from 'node:path';
import ts from '/tmp/di-bag-replacement-spike/node_modules/typescript/lib/typescript.js';
const variant=process.argv[2];
const probe=path.resolve('tests/dependency-shortcuts-minimal-review.ts');
const source=fs.readFileSync('/tmp/di-bag-dependency-shortcuts-review/minimal.ts','utf8');
const localSnapshot=`/tmp/di-bag-dependency-shortcuts-review/${variant}.ts`;
const snapshot=fs.existsSync(localSnapshot)?localSnapshot:`/tmp/di-bag-empty-dependency-probe/${variant==='key-first-hypothesis'?'cached-finite':variant}.ts`;
let types=fs.readFileSync(snapshot,'utf8');
if(variant==='key-first-hypothesis')types=types.replace('type RetainedTokenNeeds<E extends Entry> = E extends Entry', "type RetainedTokenNeeds<E extends Entry> = [E['key']] extends [never] ? never : E extends Entry");
const virtual=new Map([[probe,source],[path.resolve('src/types.ts'),types]]);
const options={strict:true,noEmit:true,skipLibCheck:true,noUncheckedIndexedAccess:true,exactOptionalPropertyTypes:true,target:ts.ScriptTarget.ES2022,module:ts.ModuleKind.NodeNext,moduleResolution:ts.ModuleResolutionKind.NodeNext,types:[]};
const host=ts.createCompilerHost(options),get=host.getSourceFile.bind(host);
host.getSourceFile=(file,version,...rest)=>virtual.has(file)?ts.createSourceFile(file,virtual.get(file),version,true):get(file,version,...rest);
const program=ts.createProgram([probe],options,host),checker=program.getTypeChecker();
const diagnostics=ts.getPreEmitDiagnostics(program).map(d=>({code:d.code,file:d.file?.fileName,start:d.start,line:d.file.getLineAndCharacterOfPosition(d.start).line+1,message:ts.flattenDiagnosticMessageText(d.messageText,'\n')}));
console.log(JSON.stringify({variant,version:ts.version,diagnostics,source},null,2));
