import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import { resolve } from 'node:path';
import { performance } from 'node:perf_hooks';
const { DiBag } = createRequire(import.meta.url)(resolve(process.argv[2]));
const scenario = process.argv[3], count = Number(process.argv[4]), sample = Number(process.argv[5]);
const raw = DiBag.factory(() => 1, { acquisition: 'raw' });
const token = DiBag.token(Symbol('group')).of();
globalThis.gc(); const before = process.memoryUsage().heapUsed;
const start = performance.now();
let builder = DiBag.module();
for (let i = 0; i < count; i++) builder = scenario === 'module-local-incremental' ? builder.add({ [`p${i}`]: raw }) : builder.contribute(token, raw);
const module = builder.exports(scenario === 'module-local-incremental' ? ['p0'] : []);
const elapsedMs = performance.now() - start;
globalThis.gc(); const retainedHeapBytes = process.memoryUsage().heapUsed - before;
const bag = DiBag.begin().install(module).end();
if (scenario === 'module-local-incremental') assert.equal(bag.resolve('p0'), 1);
else assert.equal(bag.resolveAll(token).length, count);
await bag.close();
console.log(JSON.stringify({ scenario, count, sample, node: process.version, elapsedMs, retainedHeapBytes }));
