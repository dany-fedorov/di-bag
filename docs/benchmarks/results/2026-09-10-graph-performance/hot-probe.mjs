import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import { resolve } from 'node:path';
import { performance } from 'node:perf_hooks';
const { DiBag } = createRequire(import.meta.url)(resolve(process.argv[2]));
const count = Number(process.argv[3]), sample = Number(process.argv[4]);
const raw = create => DiBag.factory(create, { acquisition: 'raw' });
const bindings = Object.fromEntries(Array.from({ length: count }, (_, i) => [`p${i}`, raw(() => i)]));
bindings.reader = raw(deps => () => deps.p0);
const bag = DiBag.begin().add(bindings).end();
for (let i = 0; i < count; i++) assert.equal(bag.resolve(`p${i}`), i);
const read = bag.resolve('reader');
for (let i = 0; i < 100000; i++) { read(); bag.resolve('p0'); }
const iterations = 500000;
let start = performance.now();
for (let i = 0; i < iterations; i++) assert.equal(read(), 0);
const proxyMs = performance.now() - start;
start = performance.now();
for (let i = 0; i < iterations; i++) assert.equal(bag.resolve('p0'), 0);
const directMs = performance.now() - start;
await bag.close();
console.log(JSON.stringify({ scenario: 'fully-warm-reads', count, sample, node: process.version, iterations, proxyMs, directMs }));
